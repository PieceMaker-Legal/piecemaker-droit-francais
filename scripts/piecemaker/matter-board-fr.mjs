export function traduire(source) {
  const trouves = [];
  const tries = [...traductions].sort((a, b) => b[0].length - a[0].length);
  for (const [anglais, francais, attendu] of tries) {
    let nombre = 0;
    for (let i = source.indexOf(anglais); i >= 0; i = source.indexOf(anglais, i + anglais.length)) {
      nombre++;
      const fin = i + anglais.length;
      const englobant = trouves.find((t) => t.debut <= i && fin <= t.fin);
      if (englobant) continue;
      if (trouves.some((t) => i < t.fin && t.debut < fin)) throw new Error('motifs qui se chevauchent : ' + anglais);
      trouves.push({ debut: i, fin, francais });
    }
    if (nombre === 0) throw new Error('motif absent : ' + anglais);
    if (nombre !== attendu) throw new Error(`motif trouvé ${nombre} fois au lieu de ${attendu} : ${anglais}`);
  }
  trouves.sort((a, b) => a.debut - b.debut);
  let sortie = '';
  let position = 0;
  for (const t of trouves) {
    sortie += source.slice(position, t.debut) + t.francais;
    position = t.fin;
  }
  return sortie + source.slice(position);
}
